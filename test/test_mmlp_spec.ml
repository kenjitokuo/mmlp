(* End-to-end computed answers.                                        *)

let bind_result result f =
  match result with Ok v -> f v | Error e -> Error e

let rec add_term_signature signature = function
  | Syntax.Var _ | Syntax.Param _ -> Ok signature
  | Syntax.Const name -> Signature.add_constant signature name
  | Syntax.Fun (name, arguments) ->
      bind_result
        (Signature.add_function signature name (List.length arguments))
        (fun signature ->
          List.fold_left
            (fun r a -> bind_result r (fun s -> add_term_signature s a))
            (Ok signature) arguments)

let rec add_formula_signature signature = function
  | Syntax.Bottom -> Ok signature
  | Syntax.Atom (name, arguments) ->
      bind_result
        (Signature.add_predicate signature name (List.length arguments))
        (fun signature ->
          List.fold_left
            (fun r a -> bind_result r (fun s -> add_term_signature s a))
            (Ok signature) arguments)
  | Syntax.Not f | Syntax.Forall (_, f) | Syntax.Exists (_, f)
  | Syntax.Box (_, f) | Syntax.Diamond (_, f) ->
      add_formula_signature signature f
  | Syntax.And (l, r) | Syntax.Or (l, r) | Syntax.Imp (l, r) ->
      bind_result (add_formula_signature signature l)
        (fun s -> add_formula_signature s r)

type run = {
  program : string list;
  query : string;
  answers : string list;
  axioms : Modal_axiom.t list;
  max_index : int;
  depth : int;
}

let run ?(focused = true) spec =
  let parse s = get_ok (Parser.parse_formula ~max_modal_index:spec.max_index s) in
  let query = parse spec.query in
  let program = List.map parse spec.program in
  let signature =
    get_ok
      (List.fold_left
         (fun r f -> bind_result r (fun s -> add_formula_signature s f))
         (Ok Signature.empty) (query :: program))
  in
  let environment =
    get_ok
      (Environment.create ~max_modal_index:spec.max_index ~signature
         ~axioms:(Modal_axiom.Set.of_list spec.axioms))
  in
  let answers =
    get_ok
      ((if focused then Execution.focused_answers_within_depth
        else Execution.answers_within_depth)
         ~environment ~program ~query ~answer_variables:spec.answers
         ~depth:spec.depth)
  in
  List.map (fun t -> t.Trusted_answer.answer) answers

let spec ?(program = []) ?(answers = []) ?(axioms = []) ?(max_index = 1)
    ~depth query =
  { program; query; answers; axioms; max_index; depth }

let succeeds ?focused s = run ?focused s <> []

let verbose = Sys.getenv_opt "MMLP_SPEC_VERBOSE" <> None

let timed name f =
  let start = Sys.time () in
  let result = f () in
  if verbose then Printf.eprintf "%6.2fs  %s\n%!" (Sys.time () -. start) name;
  result

let both name s expected =
  check (name ^ " (focused)")
    (timed (name ^ " (focused)") (fun () -> succeeds s) = expected);
  check (name ^ " (unfocused)")
    (timed (name ^ " (unfocused)") (fun () -> succeeds ~focused:false s)
     = expected)

(* Example: shared answer across a program disjunction. *)
let () =
  both "disjunctive program has no substitution answer"
    (spec ~program:["p(c1) or p(c2)"] ~answers:["X"] ~depth:4 "p(X)")
    false;
  both "disjunctive program proves the existential query"
    (spec ~program:["p(c1) or p(c2)"] ~depth:4 "exists x. p(x)")
    true

