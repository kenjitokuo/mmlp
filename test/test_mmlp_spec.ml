(* Certificate--Horn equivalence on random nested trees.               *)

type tree = {
  sequent : Nested_sequent.t;
  positions : Nested_sequent.position list;
  edges : (Nested_sequent.position * int * Nested_sequent.position) list;
}

let random_tree ~max_index ~size =
  let root, supply =
    Nested_sequent.fresh_position Nested_sequent.initial_supply
  in
  let initial =
    { Nested_sequent.position = root; formulas = []; children = [] }
  in
  let rec grow n tree supply =
    if n = 0 then tree
    else
      let parent =
        List.nth tree.positions (Random.int (List.length tree.positions))
      in
      let index = 1 + Random.int max_index in
      match
        Nested_sequent.add_empty_child
          supply tree.sequent parent (modality ~max_index index)
      with
      | None -> failwith "random_tree: add_empty_child failed"
      | Some (sequent, child, supply) ->
          grow (n - 1)
            { sequent;
              positions = tree.positions @ [child];
              edges = (parent, index, child) :: tree.edges }
            supply
  in
  grow size { sequent = initial; positions = [root]; edges = [] } supply

(* Least relation family containing the explicit edges and closed
   under the frame clauses of the selected nonserial schemes. *)
let horn_closure ~positions ~edges axioms =
  let module R = Set.Make (struct
    type t = int * int * int
    let compare = compare
  end) in
  let id p = Nested_sequent.position_number p in
  let ids = List.map id positions in
  let index m = Syntax.modal_index_number m in
  let start =
    List.fold_left
      (fun r (u, i, v) -> R.add (i, id u, id v) r)
      R.empty edges
  in
  let step r =
    let facts = R.elements r in
    let out = ref r in
    let add f = out := R.add f !out in
    let has i u v = R.mem (i, u, v) r in
    List.iter
      (fun axiom ->
        match axiom with
        | Modal_axiom.D _ -> ()
        | Modal_axiom.T i ->
            List.iter (fun u -> add (index i, u, u)) ids
        | Modal_axiom.I (i, j) ->
            List.iter
              (fun (l, u, v) -> if l = index j then add (index i, u, v))
              facts
        | Modal_axiom.B (i, j) ->
            List.iter
              (fun (l, u, v) -> if l = index i then add (index j, v, u))
              facts
        | Modal_axiom.Four (i, j, k) ->
            List.iter
              (fun (l, u, v) ->
                if l = index j then
                  List.iter
                    (fun w -> if has (index k) v w then add (index i, u, w))
                    ids)
              facts
        | Modal_axiom.Five (i, j, k) ->
            List.iter
              (fun (l, u, v) ->
                if l = index j then
                  List.iter
                    (fun w -> if has (index i) u w then add (index k, v, w))
                    ids)
              facts)
      (Modal_axiom.Set.elements axioms);
    !out
  in
  let rec fix r =
    let r' = step r in
    if R.equal r r' then r else fix r'
  in
  let closed = fix start in
  fun i u v -> R.mem (i, id u, id v) closed

let random_module ~max_index =
  let m () = modality ~max_index (1 + Random.int max_index) in
  let pick () =
    match Random.int 5 with
    | 0 -> Modal_axiom.T (m ())
    | 1 -> Modal_axiom.I (m (), m ())
    | 2 -> Modal_axiom.B (m (), m ())
    | 3 -> Modal_axiom.Four (m (), m (), m ())
    | _ -> Modal_axiom.Five (m (), m (), m ())
  in
  let rec build n acc =
    if n = 0 then acc else build (n - 1) (Modal_axiom.Set.add (pick ()) acc)
  in
  build (Random.int 4) Modal_axiom.Set.empty

let () =
  Random.init 20260801;
  let max_index = 2 in
  for _ = 1 to 300 do
    let tree = random_tree ~max_index ~size:(Random.int 5) in
    let axioms = random_module ~max_index in
    let grammar = Grammar.of_axioms axioms in
    let horn =
      horn_closure ~positions:tree.positions ~edges:tree.edges axioms
    in
    for index = 1 to max_index do
      let i = modality ~max_index index in
      List.iter
        (fun u ->
          List.iter
            (fun v ->
              let found =
                Certificate_search.find
                  ~grammar ~sequent:tree.sequent ~modality:i
                  ~source:u ~target:v
              in
              check "certificate exists iff Horn closure contains the pair"
                ((found <> None) = horn index u v);
              match found with
              | None -> ()
              | Some certificate ->
                  check "returned certificate is valid"
                    (Modal_certificate.valid
                       ~grammar ~sequent:tree.sequent ~modality:i
                       ~source:u ~target:v certificate))
            tree.positions)
        tree.positions
    done
  done

