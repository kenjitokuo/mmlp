let set = S.of_list

let flex_with ~permission supply =
  Symbolic_term.fresh_auxiliary supply ~permission

let deref mu v = Symbolic_substitution.apply mu (Symbolic_term.Flex v)

let solve supply equations =
  Scoped_unification.solve ~supply equations

let () =
  let x, s = flex_with ~permission:S.empty Symbolic_term.initial_supply in
  let y, s = flex_with ~permission:S.empty s in
  (* Flex-flex: the selected (left) variable is bound. *)
  begin
    match solve s [Symbolic_term.Flex x, Symbolic_term.Flex y] with
    | Scoped_unification.Unsolvable -> check "flex-flex solvable" false
    | Scoped_unification.Solved (mu, _) ->
        check "flex-flex binds the left variable"
          (Symbolic_substitution.find_opt mu x = Some (Symbolic_term.Flex y)
           && Symbolic_substitution.find_opt mu y = None)
  end;
  (* Orient: t = X with t rigid. *)
  begin
    match solve s [Symbolic_term.Const "c", Symbolic_term.Flex x] with
    | Scoped_unification.Unsolvable -> check "orient solvable" false
    | Scoped_unification.Solved (mu, _) ->
        check "orient then bind" (deref mu x = Symbolic_term.Const "c")
  end;
  (* Delete. *)
  begin
    match solve s [Symbolic_term.Flex x, Symbolic_term.Flex x] with
    | Scoped_unification.Unsolvable -> check "delete" false
    | Scoped_unification.Solved (mu, _) ->
        check "delete leaves identity" (Symbolic_substitution.bindings mu = [])
  end;
  (* Occurs failure. *)
  check "occurs failure"
    (solve s
       [Symbolic_term.Flex x, Symbolic_term.Fun ("f", [Symbolic_term.Flex x])]
     = Scoped_unification.Unsolvable);
  (* Clash on head symbol, arity, and rigid nullary symbols. *)
  let clashes =
    [ Symbolic_term.Fun ("f", [Symbolic_term.Const "c"]),
      Symbolic_term.Fun ("g", [Symbolic_term.Const "c"]);
      Symbolic_term.Fun ("f", [Symbolic_term.Const "c"]),
      Symbolic_term.Fun ("f", [Symbolic_term.Const "c"; Symbolic_term.Const "c"]);
      Symbolic_term.Const "c", Symbolic_term.Const "d";
      Symbolic_term.Param "a", Symbolic_term.Param "b";
      Symbolic_term.Var "x", Symbolic_term.Const "c";
      Symbolic_term.Var "x", Symbolic_term.Param "a" ]
  in
  List.iter
    (fun equation ->
      check "clash" (solve s [equation] = Scoped_unification.Unsolvable))
    clashes

let () =
  let a = set ["a"] in
  let x, s = flex_with ~permission:S.empty Symbolic_term.initial_supply in
  let y, s = flex_with ~permission:a s in
  (* Forbidden parameter failure. *)
  check "forbidden parameter"
    (solve s [Symbolic_term.Flex x, Symbolic_term.Param "a"]
     = Scoped_unification.Unsolvable);
  (* Bind a variable with a larger permission to one with a smaller. *)
  begin
    match solve s [Symbolic_term.Flex y, Symbolic_term.Flex x] with
    | Scoped_unification.Unsolvable -> check "bind to smaller permission" false
    | Scoped_unification.Solved (mu, _) ->
        check "bind Y := X when pi(X) is included in pi(Y)"
          (Symbolic_substitution.find_opt mu y = Some (Symbolic_term.Flex x))
  end;
  (* Permission restriction: X = Y with pi(Y) not included in pi(X). *)
  begin
    match solve s [Symbolic_term.Flex x, Symbolic_term.Flex y] with
    | Scoped_unification.Unsolvable -> check "permission restriction" false
    | Scoped_unification.Solved (mu, _) ->
        let vx = deref mu x and vy = deref mu y in
        check "restriction unifies both sides" (vx = vy);
        match vx with
        | Symbolic_term.Flex z ->
            check "restricted variable is fresh auxiliary"
              (not (Symbolic_term.equal_flexible z x)
               && not (Symbolic_term.equal_flexible z y)
               && Symbolic_term.kind z = Symbolic_term.Auxiliary);
            check "restricted permission is the intersection"
              (S.is_empty (Symbolic_term.permission z))
        | _ -> check "restriction yields a residual flexible variable" false
  end;
  (* Indirect scope violation: X = f(Y), Y = a with pi(X) empty. *)
  check "indirect scope violation fails"
    (solve s
       [ Symbolic_term.Flex x, Symbolic_term.Fun ("f", [Symbolic_term.Flex y]);
         Symbolic_term.Flex y, Symbolic_term.Param "a" ]
     = Scoped_unification.Unsolvable);
  (* The same constraints without the parameter succeed. *)
  check "indirect binding without parameter succeeds"
    (solve s
       [ Symbolic_term.Flex x, Symbolic_term.Fun ("f", [Symbolic_term.Flex y]);
         Symbolic_term.Flex y, Symbolic_term.Const "c" ]
     <> Scoped_unification.Unsolvable)

