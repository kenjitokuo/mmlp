(* NNF translations.                                                   *)

let () =
  let i = modality ~max_index:1 1 in
  let p = Syntax.Atom ("p", []) in
  let q = Syntax.Atom ("q", []) in
  let pp = Syntax.PosAtom ("p", []) in
  let np = Syntax.NegAtom ("p", []) in
  let pq = Syntax.PosAtom ("q", []) in
  let nq = Syntax.NegAtom ("q", []) in
  let px = Syntax.Atom ("p", [Syntax.Var "x"]) in
  let ppx = Syntax.PosAtom ("p", [Syntax.Var "x"]) in
  let npx = Syntax.NegAtom ("p", [Syntax.Var "x"]) in
  let cases =
    [ "atom", p, pp, np;
      "bottom", Syntax.Bottom, Syntax.CoreBottom, Syntax.CoreTop;
      "not", Syntax.Not p, np, pp;
      "and", Syntax.And (p, q),
        Syntax.CoreAnd (pp, pq), Syntax.CoreOr (np, nq);
      "or", Syntax.Or (p, q),
        Syntax.CoreOr (pp, pq), Syntax.CoreAnd (np, nq);
      "imp", Syntax.Imp (p, q),
        Syntax.CoreOr (np, pq), Syntax.CoreAnd (pp, nq);
      "forall", Syntax.Forall ("x", px),
        Syntax.CoreForall ("x", ppx), Syntax.CoreExists ("x", npx);
      "exists", Syntax.Exists ("x", px),
        Syntax.CoreExists ("x", ppx), Syntax.CoreForall ("x", npx);
      "box", Syntax.Box (i, p),
        Syntax.CoreBox (i, pp), Syntax.CoreDiamond (i, np);
      "diamond", Syntax.Diamond (i, p),
        Syntax.CoreDiamond (i, pp), Syntax.CoreBox (i, np) ]
  in
  List.iter
    (fun (name, source, plus, minus) ->
      check ("nnf+ " ^ name) (Nnf.nnf_plus source = plus);
      check ("nnf- " ^ name) (Nnf.nnf_minus source = minus))
    cases;
  (* Double negation is removed and implication nests correctly. *)
  check "nnf+ double negation"
    (Nnf.nnf_plus (Syntax.Not (Syntax.Not p)) = pp);
  check "nnf- nested implication"
    (Nnf.nnf_minus (Syntax.Imp (p, Syntax.Imp (q, p)))
     = Syntax.CoreAnd (pp, Syntax.CoreAnd (pq, np)))

