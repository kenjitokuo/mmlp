(* One-way matching of [pattern] onto [target]; flexible variables of
   [pattern] are the only pattern variables. *)
let rec matches binding pattern target =
  match pattern, target with
  | Symbolic_term.Flex v, _ ->
      begin
        match List.find_opt (fun (w, _) -> Symbolic_term.equal_flexible v w) binding with
        | Some (_, t) -> if t = target then Some binding else None
        | None -> Some ((v, target) :: binding)
      end
  | Symbolic_term.Fun (f, ps), Symbolic_term.Fun (g, ts)
    when String.equal f g && List.length ps = List.length ts ->
      List.fold_left2
        (fun acc p t ->
          match acc with None -> None | Some b -> matches b p t)
        (Some binding) ps ts
  | _ -> if pattern = target then Some binding else None

let () =
  Random.init 4242;
  let permissions = [| S.empty; set ["a"]; set ["a"; "b"]; set ["b"] |] in
  let ground =
    [ Symbolic_term.Const "c";
      Symbolic_term.Const "d";
      Symbolic_term.Param "a";
      Symbolic_term.Param "b";
      Symbolic_term.Fun ("f", [Symbolic_term.Const "c"]);
      Symbolic_term.Fun ("f", [Symbolic_term.Param "a"]);
      Symbolic_term.Fun ("g", [Symbolic_term.Const "c"; Symbolic_term.Param "b"]) ]
  in
  for _ = 1 to 400 do
    let vars, supply =
      List.fold_left
        (fun (vars, supply) _ ->
          let v, supply =
            flex_with
              ~permission:permissions.(Random.int (Array.length permissions))
              supply
          in
          (vars @ [v], supply))
        ([], Symbolic_term.initial_supply)
        [1; 2; 3]
    in
    let rec random_term depth =
      match Random.int (if depth = 0 then 4 else 6) with
      | 0 -> Symbolic_term.Flex (List.nth vars (Random.int 3))
      | 1 -> Symbolic_term.Const (if Random.bool () then "c" else "d")
      | 2 -> Symbolic_term.Param (if Random.bool () then "a" else "b")
      | 3 -> Symbolic_term.Flex (List.nth vars (Random.int 3))
      | 4 -> Symbolic_term.Fun ("f", [random_term (depth - 1)])
      | _ -> Symbolic_term.Fun ("g", [random_term (depth - 1); random_term (depth - 1)])
    in
    let equations =
      List.init (1 + Random.int 3) (fun _ -> random_term 2, random_term 2)
    in
    let result = solve supply equations in
    (* Every admissible ground solution over a small universe. *)
    let rec assignments = function
      | [] -> [[]]
      | v :: rest ->
          List.concat_map
            (fun t ->
              if S.subset (Symbolic_term.proof_parameters t) (Symbolic_term.permission v)
              then List.map (fun a -> (v, t) :: a) (assignments rest)
              else [])
            ground
    in
    let apply_assignment a t =
      let rec go = function
        | Symbolic_term.Flex v ->
            (match List.find_opt (fun (w, _) -> Symbolic_term.equal_flexible v w) a with
             | Some (_, t) -> t
             | None -> Symbolic_term.Flex v)
        | Symbolic_term.Fun (f, ts) -> Symbolic_term.Fun (f, List.map go ts)
        | t -> t
      in
      go t
    in
    let solutions =
      List.filter
        (fun a ->
          List.for_all
            (fun (l, r) -> apply_assignment a l = apply_assignment a r)
            equations)
        (assignments vars)
    in
    match result with
    | Scoped_unification.Unsolvable ->
        check "unification fails only without admissible solutions"
          (solutions = [])
    | Scoped_unification.Solved (mu, _) ->
        check "computed unifier solves every equation"
          (List.for_all
             (fun (l, r) ->
               Symbolic_substitution.apply mu l = Symbolic_substitution.apply mu r)
             equations);
        (* Permission safety, stated independently of the library:
           Par(t) is included in pi(X) and pi(Y) in pi(X) for every
           flexible Y of t. *)
        let safe v t =
          let pv = Symbolic_term.permission v in
          S.subset (Symbolic_term.proof_parameters t) pv
          && List.for_all
               (fun y -> S.subset (Symbolic_term.permission y) pv)
               (Symbolic_term.flexible_variables t)
        in
        check "computed unifier preserves scope"
          (List.for_all
             (fun (v, t) -> safe v t)
             (Symbolic_substitution.bindings mu));
        check "computed unifier is acyclic and idempotent"
          (List.for_all
             (fun (_, t) -> Symbolic_substitution.apply mu t = t)
             (Symbolic_substitution.bindings mu));
        List.iter
          (fun a ->
            let factors =
              List.fold_left
                (fun acc v ->
                  match acc with
                  | None -> None
                  | Some binding ->
                      matches binding (deref mu v) (apply_assignment a (Symbolic_term.Flex v)))
                (Some []) vars
            in
            check "admissible solution factors through the computed unifier"
              (factors <> None))
          solutions
  done

