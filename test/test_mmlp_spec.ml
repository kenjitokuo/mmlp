(* Closed semi-Thue productions.                                       *)

let () =
  let i = modality ~max_index:3 1 in
  let j = modality ~max_index:3 2 in
  let k = modality ~max_index:3 3 in
  let f x = Modal_symbol.Forward x in
  let b x = Modal_symbol.Backward x in
  let production lhs rhs = { Grammar.lhs; rhs } in
  let expected_for axiom =
    match axiom with
    | Modal_axiom.D _ -> []
    | Modal_axiom.T i -> [production [f i] []; production [b i] []]
    | Modal_axiom.I (i, j) ->
        [production [f i] [f j]; production [b i] [b j]]
    | Modal_axiom.B (i, j) ->
        [production [b j] [f i]; production [f j] [b i]]
    | Modal_axiom.Four (i, j, k) ->
        [production [f i] [f j; f k]; production [b i] [b k; b j]]
    | Modal_axiom.Five (i, j, k) ->
        [production [f k] [b j; f i]; production [b k] [b i; f j]]
  in
  let axioms =
    [ Modal_axiom.D i;
      Modal_axiom.T j;
      Modal_axiom.I (i, j);
      Modal_axiom.B (i, j);
      Modal_axiom.Four (i, j, k);
      Modal_axiom.Five (i, j, k) ]
  in
  List.iter
    (fun axiom ->
      let actual =
        Grammar.of_axioms (Modal_axiom.Set.singleton axiom)
      in
      let expected =
        Grammar.Production_set.of_list (expected_for axiom)
      in
      check "grammar productions of a single scheme"
        (Grammar.Production_set.equal actual expected))
    axioms;
  let all = Grammar.of_axioms (Modal_axiom.Set.of_list axioms) in
  check "grammar is closed under converse"
    (Grammar.Production_set.for_all
       (fun p ->
         Grammar.Production_set.mem (Grammar.converse_production p) all)
       all)

