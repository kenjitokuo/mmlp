(* Specification tests.

   Each group below checks one definition or theorem of the declarative
   and operational specification of MMLP against the implementation:

   - the NNF translations, clause by clause;
   - the closed semi-Thue productions generated by each modal scheme;
   - the equivalence between certificate reachability and the Horn
     closure of the selected frame clauses, on random nested trees;
   - the individual rewrites of scoped unification, and the
     termination / failure / most-general-unifier properties checked
     against a brute-force enumeration of admissible solutions;
   - end-to-end computed answers for the diagnostic examples, for the
     index conventions of every modal family, and for regressions. *)

open Mmlp

let failures = ref 0

let check name condition =
  if not condition then begin
    incr failures;
    prerr_endline ("FAILED: " ^ name)
  end

let get_ok = function
  | Ok value -> value
  | Error message -> failwith message

let modality ~max_index index =
  get_ok (Syntax.make_modal_index ~max_index index)

module S = Substitution.String_set

